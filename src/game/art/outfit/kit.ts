/**
 * Одежда: собственный слой поверх голого тела, ряды торса 20..33.
 * Символы: 6 — ткань, 7 — её тень, 8 — вторая ткань (рубашка, подкладка,
 * вставка), 9 — низ (брюки, юбка), B и C — акцент и его тень.
 *
 * Настоящий силуэт работает сильнее любого цвета: пиджак виден со спины,
 * юбка — в профиль, а майка оставляет открытыми плечи, и человек в ней
 * сложён иначе, чем человек в пальто. Ключ к этому — длина рукава. Тело
 * нарисовано с руками вдоль корпуса; ряд во всю ширину закрывает их
 * тканью, узкий ряд оставляет открытыми.
 *
 * Ноги — не рисунок, а правило. Нарисованные строками, брюки держались
 * ровно до тех пор, пока ноги стояли на месте: стоило развести их в
 * шаге, и штанина оставалась висеть в воздухе. Поэтому одежда только
 * говорит, чем ноги одеты, а красит их сборка — по тому силуэту, который
 * в этом кадре у ног на самом деле.
 */
export type OutfitStyle =
  | 'tee'
  | 'tank'
  | 'jacket'
  | 'hoodie'
  | 'suit'
  | 'dress'
  | 'crop'
  | 'track'
  | 'coat';

/** Чем одеты ноги: брюками до пят, юбкой до колена или ничем. */
